"""在「启动」文件夹写入开机自启项（GBK 编码，兼容 cmd 中文路径）。

删除自启：直接删掉 %APPDATA%\\Microsoft\\Windows\\Start Menu\\Programs\\Startup\\WeChatWorkHub.bat
或运行本脚本加 --remove 参数。

为什么改由本脚本根据自身位置解析项目目录：
    * 项目可能在任意磁盘/路径，写死 D:\\path-to-project\\... 在别人机器上必然失效；
    * 自启项内容由 launch.py 兜底（找 Python、查依赖、起后台服务、等端口），
      不再依赖历史上不存在的 `后台启动.bat`。
"""

from __future__ import annotations

import sys
from pathlib import Path

PROJECT = str(Path(__file__).resolve().parents[1])
STARTUP_DIR = (
    Path.home()
    / "AppData"
    / "Roaming"
    / "Microsoft"
    / "Windows"
    / "Start Menu"
    / "Programs"
    / "Startup"
)
TARGET = STARTUP_DIR / "WeChatWorkHub.bat"

# 开机时用与 一键启动.bat 相同的顺序找 Python（PATH 上的 python → py -3 →
# 默认安装目录里版本号最高的），再把工作交给 tools/launch.py。
BODY = f"""@echo off
chcp 936 >nul
rem auto-start WeChat Work Hub background service at logon
rem generated by tools/make_startup_entry.py - do not edit by hand
set "PYTHONIOENCODING=gbk:replace"
cd /d "{PROJECT}"

set "PY="
python -V >nul 2>nul
if not errorlevel 1 set "PY=python"

if not defined PY (
  py -3 -V >nul 2>nul
  if not errorlevel 1 set "PY=py -3"
)

if not defined PY (
  for /f "delims=" %%D in ('dir /b /ad /o-n "%LOCALAPPDATA%\\Programs\\Python\\Python3*" 2^>nul') do (
    if not defined PY if exist "%LOCALAPPDATA%\\Programs\\Python\\%%D\\python.exe" set "PY=%LOCALAPPDATA%\\Programs\\Python\\%%D\\python.exe"
  )
)

if not defined PY (
  for /f "delims=" %%D in ('dir /b /ad /o-n "C:\\Program Files\\Python3*" 2^>nul') do (
    if not defined PY if exist "C:\\Program Files\\%%D\\python.exe" set "PY=C:\\Program Files\\%%D\\python.exe"
  )
)

if not defined PY exit /b 1

"%PY%" "tools\\launch.py" --no-browser
"""


def main(argv: list[str]) -> int:
    """写入或删除自启项。"""
    if "--remove" in argv:
        if TARGET.exists():
            TARGET.unlink()
            print("已删除开机自启：", TARGET)
        else:
            print("没有找到自启项，无需删除")
        return 0

    if not STARTUP_DIR.exists():
        print("找不到「启动」文件夹：", STARTUP_DIR)
        return 1
    if not Path(PROJECT).exists():
        print("项目目录不存在：", PROJECT)
        return 1

    TARGET.write_text(BODY, encoding="gbk")
    print("已写入开机自启：", TARGET)
    print("内容：")
    print(TARGET.read_text(encoding="gbk"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))